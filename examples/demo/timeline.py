"""From narration to timing: the script's cues, then (from the voice's timings) scene
durations, subtitles and the VHS tape.

Standard library only, and imports nothing from the repo: voice.py imports it inside the
voice container, where only this folder is mounted.
"""

import re


def parse_narration(text: str) -> dict[str, list[str]]:
    """`## <scene_id>` sections, in order, each a list of cues (one per non-empty line).
    Anything before the first section is notes for humans and is ignored."""
    sections: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        heading = re.match(r"##\s+(\S+)\s*$", line)
        if heading:
            current = sections.setdefault(heading.group(1), [])
        elif current is not None and line.strip():
            current.append(line.strip())
    return sections


LEAD_IN_S = 0.3  # the scene is on screen just before its first word
SCENE_PAD_S = 0.8  # quiet after a scene's last word, so narration never runs into the next
SUBTITLE_WIDTH = 70  # characters per subtitle line: two lines fit the band under the terminal


def _r(x: float) -> float:
    return round(x, 3)


def scene_plan(timings: dict, min_durations: dict[str, float],
               beats: dict[str, int]) -> list[dict]:
    """Start, duration and beat times (seconds from the scene start) for each scene, in the
    order of `timings`. A scene lasts its narration plus padding, and at least
    `min_durations[id]`; beat k appears when cue k begins (beat 0 with the scene)."""
    plan, start = [], 0.0
    for scene_id, timing in timings.items():
        duration = max(LEAD_IN_S + timing["duration"] + SCENE_PAD_S,
                       min_durations.get(scene_id, 0.0))
        cues = timing["cues"][:beats.get(scene_id, 1)]
        beats_at = [0.0] + [_r(LEAD_IN_S + cue["start"]) for cue in cues[1:]]
        plan.append({"id": scene_id, "start": _r(start), "duration": _r(duration),
                     "beats_at": beats_at})
        start += duration
    return plan


def _stamp(seconds: float) -> str:
    ms = round(seconds * 1000)
    return f"{ms // 3_600_000:02d}:{ms // 60_000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def _wrap(text: str, width: int) -> list[str]:
    lines: list[str] = []
    for word in text.split():
        if lines and len(lines[-1]) + 1 + len(word) <= width:
            lines[-1] += " " + word
        else:
            lines.append(word)
    return lines


def srt(plan: list[dict], timings: dict) -> str:
    """Subtitles: one numbered block per cue, at the cue's place in the whole video."""
    blocks = []
    for scene in plan:
        for cue in timings[scene["id"]]["cues"]:
            start = scene["start"] + LEAD_IN_S + cue["start"]
            end = scene["start"] + LEAD_IN_S + cue["end"]
            text = "\n".join(_wrap(cue["text"], SUBTITLE_WIDTH))
            blocks.append(f"{len(blocks) + 1}\n{_stamp(start)} --> {_stamp(end)}\n{text}\n")
    return "\n".join(blocks)


def tape(plan: list[dict], session_path: str, font_size: int) -> dict[str, str]:
    """One VHS script per scene: start the player out of shot, then film it for the
    scene's duration (it stays on screen that long, so no shell prompt is filmed).
    Separate clips because VHS drops a few percent of frames on a busy machine: build.py
    stretches each clip back to its planned length, so errors cannot add up."""
    tapes = {}
    for scene in plan:
        at = ",".join(str(t) for t in scene["beats_at"])
        duration = round(scene["duration"], 2)
        command = (f"python3 examples/demo/player.py {scene['id']} --session {session_path} "
                   f"--at {at} --hold {duration}")
        tapes[scene["id"]] = "\n".join([
            "# Generated by `python -m examples.demo.build` from the narration timings.",
            f"Output build/demo/scenes/{scene['id']}.mp4", f"Set FontSize {font_size}",
            "Set Width 1280", "Set Height 600", "Set Padding 20",
            'Set Theme "Catppuccin Mocha"', "Set TypingSpeed 0", "",
            "Hide",
            f'Type "{command}"', "Enter", "Show", f"Sleep {duration}s", ""])
    return tapes


def _span(chunks: list) -> float:
    return chunks[-1][0] - chunks[0][0] if chunks else 0.0


def min_durations_from_session(session: dict) -> dict[str, float]:
    """Scenes that replay streamed chunks need time to play both streams out."""
    out = {}
    for scene_id, scene in session["scenes"].items():
        if scene.get("wire") and scene.get("app_got", {}).get("chunks"):
            out[scene_id] = (LEAD_IN_S + _span(scene["wire"][-1]["chunks"])
                             + _span(scene["app_got"]["chunks"]) + 1.0)
    return out


def voice_overrun(own: dict[str, float], plan: list[dict]) -> list[str]:
    """Scenes whose own recording would run into the next scene."""
    problems = []
    for scene in plan:
        room = scene["duration"] - LEAD_IN_S - SCENE_PAD_S / 2
        if own.get(scene["id"], 0.0) > room:
            over = own[scene["id"]] - room
            problems.append(f"{scene['id']}: your recording is {over:.1f} s too long "
                            f"(at most {room:.1f} s fits)")
    return problems
