"""Compare the exported NER candidates on the DEV split and pick the one to ship.

    python -m leakguard.ner.export --all     # first: writes models/candidates/<key>/
    python -m leakguard.ner.compare          # writes docs/evaluation/ner-comparison.md

Dev only, by design: there is no option to run this on test. Every candidate is scored
as deployed (rules + that model, merged), so a name the rules already cover inside an
email doesn't count against it.
"""

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

from leakguard.detect.engine import detect_rules
from leakguard.detect.spans import Span, merge_spans
from leakguard.entities import EntityType
from leakguard.evaluation.generate import SPLIT_SEEDS, build_split, name_form
from leakguard.evaluation.metrics import score
from leakguard.evaluation.report import measure_latency
from leakguard.evaluation.samples import Sample
from leakguard.ner.candidates import CANDIDATES
from leakguard.ner.export import CANDIDATES_DIR
from leakguard.ner.model import NameModel

OUTPUT = Path("docs/evaluation/ner-comparison.md")
THRESHOLDS = (0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90)
WITHIN_F1 = 0.01  # "within 1.0 F1 point": then the faster model wins
LOWERCASE_TRIGGER = 0.80  # build the cue-based fallback if lowercase recall is below this


@dataclass
class CandidateResult:
    key: str
    repo: str
    threshold: float  # the best one from the sweep; the rest of the row uses it
    precision: float
    recall: float
    f1: float
    negative_fp: int  # NAMEs flagged in messages that contain no personal data at all
    p50_ms: float
    p95_ms: float
    size_mb: float
    forms: dict[str, float]  # NAME recall per name form
    sweep: dict[float, float]  # threshold -> F1
    fp32: dict | None  # same measurements for the unquantised model, if exported


def select_winner(rows: list[CandidateResult]) -> str:
    """Highest F1; but if others are within 1 F1 point of it, the fastest (p95) of those."""
    best = max(row.f1 for row in rows)
    close = [row for row in rows if row.f1 >= best - WITHIN_F1]
    return min(close, key=lambda row: row.p95_ms).key


def _name_scores(ev) -> tuple[float, float, float]:
    st = ev.by_type[EntityType.NAME]
    return st.precision, st.recall, st.f1


def _measure(model: NameModel, samples: list[Sample]) -> dict:
    """Run the model once per message (threshold 0), then sweep thresholds on the cached
    spans: grouping never depends on the score, so this equals re-running per threshold."""
    model.threshold = 0.0
    rules = {s.text: detect_rules(s.text) for s in samples}
    names = {s.text: model.detect(s.text) for s in samples}

    def detector_at(threshold: float):
        def detect(text: str) -> list[Span]:
            return merge_spans([*rules[text], *(n for n in names[text] if n.score >= threshold)])
        return detect

    sweep = {t: _name_scores(score(samples, detector_at(t)))[2] for t in THRESHOLDS}
    threshold = max(sweep, key=lambda t: (sweep[t], -t))  # ties: the lower threshold
    detect = detector_at(threshold)
    ev = score(samples, detect)
    precision, recall, f1 = _name_scores(ev)
    forms = {}
    for form in sorted({f for s in samples if (f := name_form(s.template))}):
        subset = [s for s in samples if name_form(s.template) == form]
        forms[form] = score(subset, detect).by_type[EntityType.NAME].recall
    model.threshold = threshold
    latency = measure_latency(samples, model.detect)["all"]
    negative = ev.by_category_type.get(("negative", EntityType.NAME))
    return {"threshold": threshold, "precision": precision, "recall": recall, "f1": f1,
            "negative_fp": negative.fp if negative else 0, "p50_ms": latency["p50_ms"],
            "p95_ms": latency["p95_ms"], "forms": forms, "sweep": sweep}


def evaluate_candidate(key: str, samples: list[Sample]) -> CandidateResult:
    model_dir = CANDIDATES_DIR / key
    int8 = _measure(NameModel.load(model_dir), samples)
    fp32 = None
    if (model_dir / "model.fp32.onnx").is_file():
        fp32 = _measure(NameModel.load(model_dir, model_file="model.fp32.onnx"), samples)
        fp32["size_mb"] = (model_dir / "model.fp32.onnx").stat().st_size / 1e6
    size_mb = (model_dir / "model.onnx").stat().st_size / 1e6
    return CandidateResult(key=key, repo=CANDIDATES[key].repo, size_mb=size_mb, fp32=fp32,
                           **int8)


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render_comparison(rows: list[CandidateResult], n_samples: int) -> str:
    winner = select_winner(rows)
    chosen = next(row for row in rows if row.key == winner)
    lower = chosen.forms.get("lower")
    forms = sorted({f for row in rows for f in row.forms})
    out = [
        "# NER model comparison (dev split)",
        "",
        "_Generated by `python -m leakguard.ner.compare`. Do not edit by hand._",
        "",
        (f"- Data: the **dev** split ({n_samples} messages). The test split is never used "
         "here; its numbers are only reported in [report.md](report.md)."),
        ("- Each candidate is scored as deployed: the rule detectors plus that model, "
         "merged. NAME precision/recall/F1 use the report's matching rule (same type, "
         "overlapping)."),
        ("- Each candidate gets its own score threshold: the best NAME F1 over "
         f"{', '.join(f'{t:.1f}' for t in THRESHOLDS)}."),
        "- Latency: the model alone, best of 3 runs per message, 1 CPU thread, int8.",
        ("- Not a candidate: `ai4bharat/IndicNER`. It is gated on Hugging Face (download "
         "needs a logged-in account that accepted its terms), so a stranger could not build "
         "the guard with one command."),
        "",
        "## Results",
        "",
        ("| Candidate | Model | Threshold | Precision | Recall | F1 | FP in negatives "
         "| p50 | p95 | Size (int8) |"),
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in sorted(rows, key=lambda r: -r.f1):
        out.append(f"| `{r.key}` | `{r.repo}` | {r.threshold:.1f} | {_pct(r.precision)} "
                   f"| {_pct(r.recall)} | {_pct(r.f1)} | {r.negative_fp} | {r.p50_ms:.1f} ms "
                   f"| {r.p95_ms:.1f} ms | {r.size_mb:.0f} MB |")
    out += ["", "## NAME recall by name form", "",
            "| Candidate | " + " | ".join(forms) + " |",
            "|---|" + "---:|" * len(forms)]
    for r in sorted(rows, key=lambda r: -r.f1):
        cells = [_pct(r.forms[f]) if f in r.forms else "–" for f in forms]
        out.append(f"| `{r.key}` | " + " | ".join(cells) + " |")
    out += ["", "## What int8 quantisation costs and gains", "",
            "| Candidate | F1 fp32 → int8 | p50 fp32 → int8 | Size fp32 → int8 |",
            "|---|---:|---:|---:|"]
    for r in sorted(rows, key=lambda r: -r.f1):
        if r.fp32:
            out.append(f"| `{r.key}` | {_pct(r.fp32['f1'])} → {_pct(r.f1)} "
                       f"| {r.fp32['p50_ms']:.1f} → {r.p50_ms:.1f} ms "
                       f"| {r.fp32['size_mb']:.0f} → {r.size_mb:.0f} MB |")
    out += ["", "## Threshold sweep (NAME F1, int8)", "",
            "| Candidate | " + " | ".join(f"{t:.1f}" for t in THRESHOLDS) + " |",
            "|---|" + "---:|" * len(THRESHOLDS)]
    for r in sorted(rows, key=lambda r: -r.f1):
        cells = [_pct(r.sweep[t]) if t in r.sweep else "–" for t in THRESHOLDS]
        out.append(f"| `{r.key}` | " + " | ".join(cells) + " |")
    out += ["", "## Decision", "",
            ("Rule (fixed before running): highest NAME F1 on dev; if other candidates are "
             "within 1.0 F1 point of it, the one with the lowest p95 latency among them."), "",
            f"**Selected: `{winner}`** (`{chosen.repo}`), threshold {chosen.threshold:.1f}.",
            ""]
    if lower is not None:
        needed = lower < LOWERCASE_TRIGGER
        out.append(f"Lowercase names: the selected model's dev recall on lowercase names is "
                   f"{_pct(lower)} (trigger: below {_pct(LOWERCASE_TRIGGER)}), so the "
                   f"cue-based lowercase fallback is {'needed' if needed else 'not needed'}.")
    return "\n".join(out) + "\n"


def main() -> None:
    sys.stdout.reconfigure(errors="replace")
    argparse.ArgumentParser(prog="python -m leakguard.ner.compare",
                            description=__doc__.splitlines()[0]).parse_args()
    keys = [k for k in CANDIDATES if (CANDIDATES_DIR / k / "model.onnx").is_file()]
    if not keys:
        sys.exit(f"No exported candidates in {CANDIDATES_DIR}. "
                 "Run: python -m leakguard.ner.export --all")
    dev = build_split("dev", SPLIT_SEEDS["dev"])
    rows = []
    for key in keys:
        print(f"evaluating {key} on {len(dev)} dev messages...", flush=True)
        rows.append(evaluate_candidate(key, dev))
        r = rows[-1]
        print(f"  F1 {_pct(r.f1)} at threshold {r.threshold:.1f}, p95 {r.p95_ms:.1f} ms",
              flush=True)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render_comparison(rows, len(dev)), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}; selected {select_winner(rows)}")


if __name__ == "__main__":
    main()
