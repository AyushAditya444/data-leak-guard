"""Tune the address detector on the DEV split.

    python -m leakguard.evaluation.address_tuning   # writes docs/evaluation/address-tuning.md

Dev only, by design: there is no option to run this on test. Two settings are tried, each
scored with the whole pipeline as deployed (every rule detector, plus the name model when
it is exported):

- the gap: how many characters of other text may sit between two pieces of one address;
- whether the name model's location tags count as extra place signals.

Selection rule: the highest ADDRESS F1; among settings within 1.0 F1 point of it, the one
that hides the most address characters (coverage), then the smaller gap. Location tags are
kept only if, at their best gap, they beat the best setting without them on F1 or
coverage AND do not lower precision.
"""

import sys
from collections.abc import Callable
from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path

from leakguard.config import Settings
from leakguard.detect.address import detect_address
from leakguard.detect.engine import Detector, build_detector
from leakguard.detect.gazetteer import STOPWORDS
from leakguard.entities import EntityType
from leakguard.evaluation.generate import SPLIT_SEEDS, build_split
from leakguard.evaluation.metrics import score
from leakguard.evaluation.report import measure_latency
from leakguard.evaluation.samples import Sample
from leakguard.ner.model import Entities, NameModel, NameModelError

OUTPUT = Path("docs/evaluation/address-tuning.md")
GAPS = (0, 6, 12, 18, 24, 32)
WITHIN_F1 = 0.01

Analyse = Callable[[str], Entities]


@dataclass(frozen=True)
class TuningRow:
    gap: int
    loc: bool  # location tags used as place signals
    precision: float
    recall: float
    f1: float
    coverage: float
    negatives_flagged: int  # negative messages with any ADDRESS prediction
    p95_ms: float  # the address detector alone


def _best(rows: list[TuningRow]) -> TuningRow:
    top = max(r.f1 for r in rows)
    near = [r for r in rows if r.f1 >= top - WITHIN_F1]
    return max(near, key=lambda r: (r.coverage, r.f1, -r.gap))


def select_setting(rows: list[TuningRow]) -> tuple[int, bool]:
    """(gap, use location tags), by the rule in the module docstring."""
    off = _best([r for r in rows if not r.loc])
    with_loc = [r for r in rows if r.loc]
    if with_loc:
        on = _best(with_loc)
        if (on.f1 > off.f1 or on.coverage > off.coverage) and on.precision >= off.precision:
            return on.gap, True
    return off.gap, False


def _cached(analyse: Analyse) -> Analyse:
    """Run the model once per message, however many settings are scored."""
    cache: dict[str, Entities] = {}

    def run(text: str) -> Entities:
        if text not in cache:
            cache[text] = analyse(text)
        return cache[text]

    return run


def _row(dev: list[Sample], detect: Detector, gap: int, analyse: Analyse | None) -> TuningRow:
    """Scores for one setting. `analyse` is given only when location tags are used."""
    st = score(dev, detect).by_type[EntityType.ADDRESS]
    negatives = [s for s in dev if s.category == "negative"]
    flagged = sum(any(p.type is EntityType.ADDRESS for p in detect(s.text)) for s in negatives)

    def address_only(text: str):
        locations = analyse(text).locations if analyse else ()
        return detect_address(text, locations=locations, gap=gap)

    p95 = measure_latency(dev[::10], address_only)["all"]["p95_ms"]
    return TuningRow(gap, analyse is not None, st.precision, st.recall, st.f1, st.coverage,
                     flagged, p95)


DEV_MARKER = "# Added from the dev split"


def dev_stopwords() -> list[str]:
    """Words added to the place stop list after looking at the dev split."""
    lines = files("leakguard").joinpath(STOPWORDS).read_text(encoding="utf-8").splitlines()
    marker = next((i for i, line in enumerate(lines) if line.startswith(DEV_MARKER)), None)
    if marker is None:
        return []
    return [line.strip() for line in lines[marker:] if line.strip() and not line.startswith("#")]


def _pct(x: float) -> str:
    return f"{100 * x:.1f}"


def render(rows: list[TuningRow], chosen: tuple[int, bool], n_dev: int,
           model_name: str | None) -> str:
    pipeline = "every rule detector" + (f" + name model `{model_name}`" if model_name else "")
    out = ["# Address detector tuning (dev split)", "",
           ("Generated by `python -m leakguard.evaluation.address_tuning`. Dev split only "
            f"({n_dev} messages); the test split was not used."), "",
           (f"Pipeline: {pipeline}, merged, as deployed. Matching: same type and overlapping "
            "(see report.md)."), "",
           ("Selection rule: highest ADDRESS F1; within 1.0 F1 point of it, highest coverage, "
            "then the smaller gap. Location tags are kept only if, at their best gap, they "
            "beat the best setting without them on F1 or coverage and do not lower "
            "precision."), "",
           ("| Gap | Location tags | Precision | Recall | F1 | Coverage | Negatives flagged "
            "| p95 ms (address alone) |"), "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        mark = " **(chosen)**" if (r.gap, r.loc) == chosen else ""
        out.append(f"| {r.gap}{mark} | {'on' if r.loc else 'off'} | {_pct(r.precision)} | "
                   f"{_pct(r.recall)} | {_pct(r.f1)} | {_pct(r.coverage)} | "
                   f"{r.negatives_flagged} | {r.p95_ms:.2f} |")
    gap, loc = chosen
    out += ["", f"**Chosen:** gap {gap}, location tags {'on' if loc else 'off'}."]
    if model_name is None:
        out.append("Location tags were not tried: no exported name model was found.")
    words = dev_stopwords()
    out += ["", "## Place stop list", "",
            ("Post office names matched outside addresses on dev were listed; those that "
             "are everyday English or Hinglish words, or festival names, were added to "
             "`src/leakguard/data/place_stopwords.txt` (never a word added only to fix one "
             "sample). Person surnames that are also village names were NOT added: instead, "
             "an address that overlaps a name absorbs it, so no part of the name leaks."),
            "", "Added on dev: " + (", ".join(f"`{w}`" for w in words) or "none") + "."]
    return "\n".join(out)


def main() -> None:
    sys.stdout.reconfigure(errors="replace")
    dev = build_split("dev", SPLIT_SEEDS["dev"])
    settings = Settings.from_env()
    model = None
    if settings.ner_enabled:
        try:
            model = NameModel.load(settings.ner_model_dir, settings.ner_threads)
        except NameModelError as exc:
            print(f"note: no name model ({exc}); location tags not tried", file=sys.stderr)
    analyse = _cached(model.analyse) if model else None

    rows = []
    for gap in GAPS:
        names = (lambda t: analyse(t).names) if analyse else None
        rows.append(_row(dev, build_detector(name_model=names, address_gap=gap), gap, None))
        if analyse:
            rows.append(_row(dev, build_detector(ner=analyse, address_gap=gap), gap, analyse))
        print(f"gap {gap} done", file=sys.stderr)
    chosen = select_setting(rows)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(rows, chosen, len(dev), model.name if model else None) + "\n",
                      encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}; chosen gap {chosen[0]}, location tags {chosen[1]}")


if __name__ == "__main__":
    main()
